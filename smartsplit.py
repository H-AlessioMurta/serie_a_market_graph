# Funzione per splittare i nomi
def split_nome(nome):
    parti = nome.split()
    # Controlla se la prima parte ha più di 2 caratteri
    if len(parti[0]) > 2:
        return [parti[0], ' '.join(parti[1:])]
    else:
        return [parti[0]+" "+parti[1]]

